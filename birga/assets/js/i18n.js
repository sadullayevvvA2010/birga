  let current = CONFIG.DEFAULT_LANG;

  function normalizeLang(lang) {
    if (lang && CONFIG.SUPPORTED_LANGS.includes(lang)) return lang;
    const htmlLang = document.documentElement?.getAttribute('lang');
    if (htmlLang && CONFIG.SUPPORTED_LANGS.includes(htmlLang)) return htmlLang;
    return CONFIG.DEFAULT_LANG;
  }

  function syncLanguageButtons() {
    document.querySelectorAll('[data-lang]').forEach(btn => {
      const lang = btn.getAttribute('data-lang');
      const active = lang === current;
      btn.classList.toggle('active', active);
      btn.classList.toggle('btn-primary', active);
      btn.classList.toggle('btn-ghost', !active);
      btn.setAttribute('aria-pressed', String(active));
    });
  }

  function init() {
    const saved = normalizeLang(Storage.get('lang', document.documentElement?.getAttribute('lang') || CONFIG.DEFAULT_LANG));
    current = saved;
    apply();
    document.documentElement.lang = current;
  }
  function set(lang) {
    if (!CONFIG.SUPPORTED_LANGS.includes(lang)) return;
    current = lang;
    Storage.set('lang', lang);
    apply();
    document.documentElement.lang = lang;
  }
  function get() { return current; }
  function t(key) { return dict[current]?.[key] || dict[CONFIG.DEFAULT_LANG]?.[key] || key; }
  function apply() {
    document.documentElement.lang = current;
    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder'))); });
    document.querySelectorAll('[data-i18n-title]').forEach(el => { el.setAttribute('title', t(el.getAttribute('data-i18n-title'))); });
    syncLanguageButtons();
  }
  return { init, set, get, t, apply, syncLanguageButtons };
